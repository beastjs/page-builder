test('builder drags within the screen and keeps its position across views and reopening', async ({ page }) => {
  await open(page)
  const dialog = page.getByRole('dialog')
  const handle = page.getByRole('button', { name: 'Move builder', exact: true })
  const initial = (await dialog.boundingBox())!
  const grip = (await handle.boundingBox())!
  await page.mouse.move(grip.x + grip.width / 2, grip.y + grip.height / 2)
  await page.mouse.down()
  await page.mouse.move(grip.x + grip.width / 2 + 140, grip.y + grip.height / 2 + 80, { steps: 6 })
  await page.mouse.up()
  const moved = (await dialog.boundingBox())!
  expect(moved.x).toBeCloseTo(initial.x + 140, 0)
  expect(moved.y).toBeCloseTo(initial.y + 80, 0)
  await page.getByRole('button', { name: 'Tabs', exact: true }).click()
  await page.getByRole('button', { name: /Add Tabs to a page/ }).click()
  const form = (await dialog.boundingBox())!
  expect(form.x).toBeCloseTo(moved.x, 0)
  expect(form.y).toBeCloseTo(moved.y, 0)
  await page.getByRole('button', { name: 'Close builder' }).click()
  await toggle(page)
  await expect(page.getByText('Builder ready', { exact: true })).toBeVisible()
  const reopened = (await dialog.boundingBox())!
  expect(reopened.x).toBeCloseTo(moved.x, 0)
  expect(reopened.y).toBeCloseTo(moved.y, 0)
  const header = (await handle.boundingBox())!
  await page.mouse.move(header.x + header.width / 2, header.y + header.height / 2)
  await page.mouse.down()
  await page.mouse.move(2000, 1800, { steps: 6 })
  await page.mouse.up()
  const clamped = (await dialog.boundingBox())!
  expect(clamped.x + clamped.width).toBeLessThanOrEqual(1440 - 7)
  expect(clamped.y + clamped.height).toBeLessThanOrEqual(1000 - 7)
  await page.setViewportSize({ width: 390, height: 844 })
  await expect.poll(async () => {
    const box = (await dialog.boundingBox())!
    return box.x >= 0 && box.y >= 0 && box.x + box.width <= 390 && box.y + box.height <= 844
  }).toBe(true)
})

