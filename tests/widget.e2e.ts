test('Tabs form follows the current route, searches and navigates pages, then saves typed items', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await open(page)
  await page.getByRole('button', { name: 'Tabs', exact: true }).click()
  await page.getByRole('button', { name: /Add Tabs to a page/ }).click()
  await expect(page.getByRole('combobox', { name: 'Page route', exact: true })).toHaveValue('Home · /')
  await expect(page.getByRole('button', { name: 'Review Tabs', exact: true })).toBeEnabled()
  await expect(page.getByLabel('shortLabel · Tab 1', { exact: true })).toBeVisible()
  await expect(page.getByLabel('icon · Tab 1', { exact: true }).locator('option')).toHaveCount(4)
  await page.getByLabel('label · Tab 1', { exact: true }).fill('Overview')
  await page.getByLabel('icon · Tab 1', { exact: true }).selectOption({ label: 'menu' })
  const search = page.getByRole('combobox', { name: 'Page route', exact: true })
  await search.fill('missing-page')
  await expect(page.getByText('No matching page routes.')).toBeVisible()
  await search.fill('/browser-test')
  await page.getByRole('option', { name: /browser-test/ }).click()
  await expect(page).toHaveURL(/\/browser-test$/)
  await expect(page.getByRole('heading', { name: 'Add Tabs', exact: true })).toBeVisible()
  await expect(page.getByRole('combobox', { name: 'Page route', exact: true })).toHaveValue(`${pageName} · /browser-test`)
  await expect(page.getByLabel('label · Tab 1', { exact: true })).toHaveValue('Overview')
  await expect(page.getByRole('button', { name: 'Review Tabs', exact: true })).toBeEnabled()
  await page.getByLabel('href · Tab 1', { exact: true }).fill('/browser-test')
  await page.getByRole('button', { name: 'Add tab item', exact: true }).click()
  await page.getByRole('button', { name: 'Remove Tab 2', exact: true }).click()
  await page.getByRole('button', { name: 'Add tab item', exact: true }).click()
  await expect(page.getByLabel('id · Tab 3', { exact: true })).toHaveValue('tab-4')
  await page.getByRole('button', { name: 'Remove Tab 3', exact: true }).click()
  await page.getByRole('button', { name: 'Remove Tab 2', exact: true }).click()
  await page.getByRole('button', { name: 'Add tab item', exact: true }).click()
  await page.getByLabel('href · Tab 2', { exact: true }).fill('/')
  await page.getByLabel('label · Tab 2', { exact: true }).fill('Home')
  await page.screenshot({ path: 'test-results/builder-add-tabs.png' })
  await page.getByRole('button', { name: 'Review Tabs', exact: true }).click()
  await expect(page.getByText('Compiles with Beast and Octane')).toBeVisible()
  await expect(page.locator('.planned-file')).toHaveCount(1)
  await page.getByRole('button', { name: 'Add Tabs', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Your tabs are ready.', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Close builder', exact: true }).click()
  await expect(page.getByRole('navigation', { name: 'Tabs', exact: true })).toBeVisible()
  await expect(page.getByRole('navigation', { name: 'Tabs', exact: true }).getByRole('link', { name: 'Overview', exact: true })).toHaveAttribute('aria-current', 'page')
  const source = await readFile(`playground/src/pages/${pageName}.btsx`, 'utf8')
  expect(source).toContain('"shortLabel":"Tab 1"')
  expect(source).toContain('"label":"Overview"')
  expect(source).toContain('"icon":"menu"')
  expect(errors).toEqual([])
})

test('an unregistered current route leaves Tabs review disabled until a page is selected', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/not-a-page')
  await toggle(page)
  await expect(page.getByText('Builder ready', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: /Add Tabs to a page/ }).click()
  await expect(page.getByRole('combobox', { name: 'Page route', exact: true })).toHaveValue('')
  await expect(page.getByRole('button', { name: 'Review Tabs', exact: true })).toBeDisabled()
  const box = await page.getByRole('dialog').boundingBox()
  expect(box!.x).toBeGreaterThanOrEqual(0)
  expect(box!.x + box!.width).toBeLessThanOrEqual(390)
  await page.screenshot({ path: 'test-results/builder-add-tabs-mobile.png' })
  await page.getByRole('combobox', { name: 'Page route', exact: true }).fill('Home')
  await page.getByRole('combobox', { name: 'Page route', exact: true }).press('Enter')
  await expect(page).toHaveURL(/\/$/)
  await expect(page.getByRole('button', { name: 'Review Tabs', exact: true })).toBeEnabled()
})
