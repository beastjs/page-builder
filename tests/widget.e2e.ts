test('compiler errors are shown and a closed scan cannot reopen the widget', async ({ page }) => {
  await open(page)
  await page.keyboard.press('Enter')
  await page.getByLabel('BTSX page source').fill('main\n   p Hello\n  p Wrong indentation')
  await page.getByRole('button', { name: 'Review page' }).click()
  await expect(page.locator('#beast-page-builder').locator('.message')).not.toBeEmpty()
  await expect(page.getByRole('button', { name: 'Create page', exact: true })).toHaveCount(0)
  await page.keyboard.press('Escape')
  await toggle(page)
  await expect(page.getByText('Getting to know your project')).toBeVisible()
  await page.keyboard.press('Escape')
  await page.waitForTimeout(1800)
  await expect(page.getByRole('dialog')).toBeHidden()
})

test('focus is trapped and restored, and the mobile panel fits', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/')
  const launcher = page.getByRole('button', { name: 'Open Beast page builder' })
  await launcher.focus()
  await launcher.click()
  await expect(page.getByText('Builder ready', { exact: true })).toBeVisible()
  for (let index = 0; index < 12; index++) {
    await page.keyboard.press(index === 0 ? 'Shift+Tab' : 'Tab')
    expect(await page.locator('#beast-page-builder').evaluate(host => host.shadowRoot!.querySelector('.panel')!.contains(host.shadowRoot!.activeElement))).toBe(true)
  }
  const box = await page.getByRole('dialog').boundingBox()
  expect(box!.x).toBeGreaterThanOrEqual(0)
  expect(box!.x + box!.width).toBeLessThanOrEqual(390)
  await page.screenshot({ path: 'test-results/builder-mobile.png' })
  await page.keyboard.press('Escape')
  await expect(launcher).toBeFocused()
})

test('reduced motion skips the waiting animation', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/')
  await toggle(page)
  await expect(page.getByText('Builder ready', { exact: true })).toBeVisible({ timeout: 1200 })
  expect(await page.locator('#beast-page-builder').locator('.panel').evaluate(element => getComputedStyle(element).animationName)).toBe('none')
})


